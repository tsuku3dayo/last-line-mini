/** 1 文字の幅（字間 1 ドットを含む）× 倍率 */
export const advance = (scale: number): number => (GLYPH_WIDTH + 1) * scale;

/** 文字列の幅（最後の字間を除く） */
export function textWidth(text: string, scale: number): number {
  return text.length === 0 ? 0 : text.length * advance(scale) - scale;
}

/** 文字のドットの位置（左上が 0, 0）。知らない文字は空白にする */
export function textPixels(text: string): { x: number; y: number }[] {
  const out: { x: number; y: number }[] = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '] ?? [];
    glyph.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') out.push({ x: i * (GLYPH_WIDTH + 1) + x, y });
    });
  });
  return out;
}
